"""Pull/research view: python -m finn.pull tcs.html

Deterministic sections render from typed rows today. LLM-dependent sections
(business snapshot, cash quality narrative, narrative vs numbers, bull vs bear)
are explicitly stubbed pending a model key - labeled, never fabricated."""
from __future__ import annotations

import html
import sys

from .ledger import growth_pct, promised_vs_delivered
from .models import Metric
from .real_seed import SOURCE_URL, tcs_filings
from .web import CSS, METRIC_LABEL, render_ledger_rows

STUB = '<div class="card" style="color:#6b655c;font-size:13px">Pending model key - this section is generated by the research agent. Retrieval and narration are stubbed offline; the typed data above is what it will ground in.</div>'


def build() -> str:
    fs = sorted(tcs_filings(), key=lambda f: f.period_end)
    latest = fs[-1]
    qoq = {m: growth_pct(fs[-1], fs[-2], m) for m in Metric}
    yoy = {m: growth_pct(fs[-1], fs[0], m) for m in Metric}

    def cell(m: Metric) -> str:
        v = latest.metric_value(m)
        return f"Rs {v.in_crore():,.0f} cr" if v else "not stated"

    def pct(x) -> str:
        return f"{x:+.1f}%" if x is not None else "n/a (not stated)"

    rows = "".join(
        f'<div class="row"><div><b>{METRIC_LABEL[m]}</b></div><div>{cell(m)}'
        f'<div class="num">QoQ {pct(qoq[m])} · YoY {pct(yoy[m])}</div></div></div>'
        for m in Metric)
    traj = "".join(
        f'<div class="row"><div>Q ended {f.period_end}<div class="num">Revenue from operations</div></div><div>Rs {f.revenue_from_operations.in_crore():,.0f} cr'
        f'<div class="num">PAT Rs {f.pat.in_crore():,.0f} cr</div></div></div>'
        for f in fs)
    ledger = promised_vs_delivered(latest.company, [], fs)
    lrows, _ = render_ledger_rows(ledger)

    return f"""<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>FINN - TCS research</title><style>{CSS}</style></head><body>
<div class="banner">PULL VIEW - real filing data, manually seeded. Source: NSE announcement archive PDF (8 Oct 2026), consolidated Ind-AS.</div>
<h1>Tata Consultancy Services</h1><div class="sub">Q2 FY27 · quarter ended 30 Sep 2026 · consolidated Ind-AS</div>
<h2>Financial snapshot</h2><div class="card ledger">{rows}</div>
<div class="num">Actuals from the results press release, p.3: <a href="{SOURCE_URL}">NSE announcement archive PDF</a></div>
<h2>Trajectory</h2><div class="card ledger">{traj}</div>
<h2>Promised vs delivered</h2><div class="card ledger">{lrows}</div>
<h2>Business snapshot</h2>{STUB}
<h2>Cash quality</h2>{STUB}
<h2>Narrative vs numbers</h2>{STUB}
<h2>Bull vs bear</h2>{STUB}
<div class="num" style="margin-top:14px">Filing: {html.escape(SOURCE_URL)}</div>
</body></html>"""


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "/downloads/finn-pull.html"
    open(out, "w").write(build())
    print(out)
